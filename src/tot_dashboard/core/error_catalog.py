# HTTP 상태 코드로 정해지는 것들. 예외 분류보다 우선한다.
_BY_STATUS: dict[int, str] = {
    401: "UG-AUTH-004",
    403: "UG-AUTH-003",
    413: "UG-FILE-001",
    415: "UG-FILE-002",
}


def classify(exc: BaseException | None = None, *, message: str = "",
             status_code: int | None = None, path: str = "") -> str:
    """예외·메시지·상태코드를 보고 오류 코드를 고른다.

    어느 것에도 걸리지 않으면 :data:`UNKNOWN` 을 준다 — **분류에 실패했다고
    기록을 버리지 않습니다.** 처음 보는 오류일수록 남겨야 하기 때문입니다.
    """
    if status_code is not None and status_code in _BY_STATUS:
        return _BY_STATUS[status_code]

    if exc is not None:
        # 상속 계층을 따라 올라가며 본다 — psycopg 예외는 여러 겹으로 감싸여 있다.
        for klass in type(exc).__mro__:
            hit = _BY_EXC_NAME.get(klass.__name__)
            if hit:
                return hit

    text = " ".join(x for x in (message, str(exc) if exc is not None else "",
                                path) if x).lower()
    if text:
        for words, code in _BY_KEYWORD:
            if all(w in text for w in words):
                return code
    return UNKNOWN
