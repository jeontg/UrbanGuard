# 화면에서 「선택 안 함」을 나타내는 값. 빈 문자열을 그대로 쓰면 폼과 DB에서
# 서로 다르게 취급되기 쉬워 상수로 둔다.
UNSET = ""


def sido_choices() -> list[tuple[str, str]]:
    """(키, 이름) 목록. 화면 선택상자에 그대로 넣는다."""
    return [(k, label) for k, (label, _bbox) in SRC.REGIONS.items()]


def sido_label(key: str | None) -> str:
    return SRC.region_label(key)


def sigungu_choices(sido: str | None) -> list[str]:
    """해당 시/도의 시·군·구. 모르는 시/도면 빈 목록."""
    return list(SIGUNGU.get(sido or "", ()))


def is_valid(sido: str | None, sigungu: str | None) -> bool:
    """저장해도 되는 조합인가.

    * 둘 다 비었으면 **허용한다** — 지역을 모르는 지점도 등록은 되어야 한다
    * 시/도 없이 구·군만 있는 것은 막는다 — 어느 시의 「중구」인지 알 수 없다
    * 구·군이 그 시/도에 없는 이름이면 막는다
    """
    sido = (sido or "").strip()
    sigungu = (sigungu or "").strip()
    if not sido:
        return not sigungu
    if sido not in SIGUNGU:
        return False
    if not sigungu:
        return True
    return sigungu in SIGUNGU[sido]


def validate(sido: str | None, sigungu: str | None) -> list[str]:
    """검증 오류를 사람이 읽는 문장으로. 없으면 빈 목록."""
    s = (sido or "").strip()
    g = (sigungu or "").strip()
    if not s and g:
        return ["시/도를 먼저 고르세요. 시/도 없이 구·군만으로는 "
                "어느 지역인지 알 수 없습니다."]
    if s and s not in SIGUNGU:
        return [f"알 수 없는 시/도입니다: {s}"]
    if s and g and g not in SIGUNGU[s]:
        return [f"{sido_label(s)}에 없는 시·군·구입니다: {g}"]
    return []


def fallback_sido(lat: float | None, lng: float | None) -> str:
    """좌표로 시/도만 유추한다. 못 하면 빈 문자열.

    **구·군은 유추하지 않는다.** 사각형으로는 구 단위를 가를 수 없고,
    틀린 구 이름은 없느니만 못하다.
    """
    return SRC.region_of(lat, lng) or ""


def label_of(sido: str | None, sigungu: str | None) -> str:
    """화면에 쓸 한 줄. 「서울특별시 강남구」 · 「부산광역시」 · 「지역 미상」."""
    s = (sido or "").strip()
    g = (sigungu or "").strip()
    if not s:
        return "지역 미상"
    return f"{sido_label(s)} {g}".strip()
